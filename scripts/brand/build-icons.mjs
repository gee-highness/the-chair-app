// Renders the Chair App logo SVGs to the PNG icons the PWA manifests use.
//   node scripts/brand/build-icons.mjs
// Needs Playwright's Chromium (already installed for the e2e tests).
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const chair = readFileSync(path.join(root, 'scripts/brand/chair.svg'), 'utf8');
const inner = chair.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
const DEFS = `<defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#1b3a57"/><stop offset="1" stop-color="#0f2236"/></linearGradient>
    <linearGradient id="cu" gradientUnits="userSpaceOnUse" x1="0" y1="90" x2="0" y2="450"><stop offset="0" stop-color="#f6b27c"/><stop offset="1" stop-color="#b4521f"/></linearGradient>
    <radialGradient id="halo" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="#f0a068" stop-opacity="0.28"/><stop offset="1" stop-color="#f0a068" stop-opacity="0"/></radialGradient>
  </defs>`;
const RING = '<circle cx="256" cy="256" r="226" fill="none" stroke="#f0a068" stroke-opacity="0.22" stroke-width="4"/>';

// Shared by the app/tab icon and the in-page <Logo>: one source, no drift.
writeFileSync(path.join(root, 'src/app/icon.svg'), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${DEFS}<rect width="512" height="512" rx="112" fill="url(#bg)"/>${RING}${inner}</svg>\n`);
writeFileSync(
  path.join(root, 'src/components/logoMarkSvg.ts'),
  `// GENERATED by scripts/brand/build-icons.mjs from scripts/brand/chair.svg. Do not edit.\nexport const LOGO_MARK_SVG = ${JSON.stringify(`${DEFS}<rect width="512" height="512" rx="112" fill="url(#bg)"/>${RING}${inner}`)};\n`
);

// (name, size, background, chair scale, accent badge)
const variants = [
  ['public/logo-192.png', 192, 'navy', 1, false],
  ['public/logo-512.png', 512, 'navy', 1, false],
  ['public/logo-maskable-512.png', 512, 'navy', 0.7, false],
  ['public/admin-icon-192.png', 192, 'cream', 1, true],
  ['public/admin-icon-512.png', 512, 'cream', 1, true],
  ['src/app/apple-icon.png', 180, 'navy', 1, false],
];

const svgFor = (bg, scale, badge) => {
  const full = scale < 1; // maskable: full-bleed square, chair kept inside the safe zone
  const fill = bg === 'navy' ? 'url(#bg)' : '#f7f3ec';
  // On cream, draw the chair in navy instead of copper.
  const mark = bg === 'navy' ? inner : inner.replace(/url\(#cu\)/g, '#0f2236').replace(/url\(#halo\)/g, 'none');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  ${DEFS}
  <rect width="512" height="512" rx="${full ? 0 : 112}" fill="${fill}"/>
  ${bg === 'navy' && !full ? RING : ''}
  <g transform="translate(${256 - 256 * scale} ${256 - 256 * scale}) scale(${scale})">${mark}</g>
  ${badge ? '<circle cx="408" cy="104" r="52" fill="#b4521f"/><path d="M386 106l16 16 30-34" fill="none" stroke="#fff" stroke-width="12" stroke-linecap="round" stroke-linejoin="round"/>' : ''}
</svg>`;
};

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium' });
for (const [file, size, bg, scale, badge] of variants) {
  const page = await browser.newPage({ viewport: { width: size, height: size } });
  await page.setContent(`<body style="margin:0;background:transparent">${svgFor(bg, scale, badge).replace('width="512" height="512"', `width="${size}" height="${size}"`)}</body>`);
  const buf = await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
  writeFileSync(path.join(root, file), buf);
  await page.close();
  console.log('wrote', file);
}
await browser.close();
